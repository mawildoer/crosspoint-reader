"""Convert the existing Paperboy artwork to the renderer's 120px, 1-bit bitmap."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
image = Image.open(root / "src/images/PaperboyIcon.png").convert("L")
image = image.resize((120, 120), Image.Resampling.LANCZOS).point(lambda value: 255 if value >= 150 else 0, mode="1")
data = image.tobytes()
assert len(data) == 1800
rows = ["  " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 20]) + "," for i in range(0, len(data), 20)]
header = "#pragma once\n#include <cstdint>\n\n// Generated by scripts/generate_paperboy_logo.py from PaperboyIcon.png.\n"
header += "static const uint8_t PaperboyLogo120[] = {\n" + "\n".join(rows) + "\n};\n"
(root / "src/images/PaperboyLogo120.h").write_text(header)
if __name__ == "__main__":
    image.save("/tmp/paperboy-sleep-logo.png")
