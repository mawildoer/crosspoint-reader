"""Extract a monochrome Paperboy mark with a white background, in logical row order."""
from pathlib import Path
from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageOps

root = Path(__file__).resolve().parent.parent
size = 384
gray = Image.open(root / "src/images/PaperboyIcon.png").convert("L")
paper = gray.point(lambda value: 255 if value >= 150 else 0)
# Separate the outside matte from enclosed ink such as the P and newspaper rules.
ImageDraw.floodfill(paper, (0, 0), 128)
silhouette = paper.point(lambda value: 0 if value == 128 else 255)
bounds = silhouette.getbbox()
assert bounds is not None
shape = ImageOps.contain(silhouette.crop(bounds), (size - 8, size - 8), Image.Resampling.LANCZOS)
details = gray.crop(bounds).resize(shape.size, Image.Resampling.LANCZOS)
shape = shape.point(lambda value: 255 if value >= 128 else 0)
ink = ImageChops.multiply(details.point(lambda value: 255 if value < 150 else 0), shape)
position = ((size - shape.width) // 2, (size - shape.height) // 2)
paperMask = Image.new("L", (size, size), 0)
paperMask.paste(shape, position)
detailsMask = Image.new("L", (size, size), 0)
detailsMask.paste(ink, position)
outline = ImageChops.subtract(paperMask, paperMask.filter(ImageFilter.MinFilter(5)))
image = ImageChops.invert(ImageChops.lighter(detailsMask, outline))
image = image.convert("1", dither=Image.Dither.NONE)
data = image.tobytes()
assert len(data) == size * size // 8
rows = ["  " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 20]) + "," for i in range(0, len(data), 20)]
header = "#pragma once\n#include <cstdint>\n\n// Generated by scripts/generate_paperboy_logo.py from PaperboyIcon.png.\n"
header += f"static constexpr int PAPERBOY_LOGO_SIZE = {size};\n"
header += "// Logical rows, MSB first; 0 is ink and 1 is white.\n"
header += "static const uint8_t PaperboyLogo[] = {\n" + "\n".join(rows) + "\n};\n"
(root / "src/images/PaperboyLogo.h").write_text(header)
if __name__ == "__main__":
    image.save("/tmp/paperboy-sleep-logo.png")
